USE ROLE ACCOUNTADMIN;
USE WAREHOUSE FINPULSE_WH;

-- 1. Create Database and 3 Schemas
CREATE OR REPLACE DATABASE FINPULSE_DB;
CREATE OR REPLACE SCHEMA FINPULSE_DB.RAW;
CREATE OR REPLACE SCHEMA FINPULSE_DB.ANALYTICS;
CREATE OR REPLACE SCHEMA FINPULSE_DB.APP_DATA;

USE SCHEMA FINPULSE_DB.RAW;

-- 2. Create File Formats & Internal Stage (Data Warehouse Badge)
CREATE OR REPLACE FILE FORMAT JSON_MARKET_FMT
  TYPE = 'JSON'
  STRIP_OUTER_ARRAY = TRUE
  IGNORE_UTF8_ERRORS = TRUE;

CREATE OR REPLACE STAGE MARKET_STAGE
  FILE_FORMAT = JSON_MARKET_FMT;

-- 3. Create Raw Landing Table (VARIANT holds semi-structured JSON)
CREATE OR REPLACE TABLE FINPULSE_DB.RAW.CRYPTO_PRICES_RAW (
  INGESTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
  SOURCE_FILE STRING,
  RAW_PAYLOAD VARIANT
);

-- 4. Create Clean Analytical Fact Table
CREATE OR REPLACE TABLE FINPULSE_DB.ANALYTICS.FACT_MARKET_PRICES (
  ASSET_ID STRING,
  SYMBOL STRING,
  ASSET_NAME STRING,
  PRICE_USD FLOAT,
  MARKET_CAP_USD FLOAT,
  VOLUME_24H_USD FLOAT,
  CHANGE_24H_PCT FLOAT,
  CAPTURED_AT TIMESTAMP_NTZ
);

-- 5. Create App Watchlist Table & Add 2 Starter Rows
CREATE OR REPLACE TABLE FINPULSE_DB.APP_DATA.USER_WATCHLIST (
  ENTRY_ID NUMBER AUTOINCREMENT START 1 INCREMENT 1,
  USER_NAME STRING,
  SYMBOL STRING,
  TARGET_PRICE_USD FLOAT,
  ALERT_TYPE STRING,
  NOTES STRING,
  CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

