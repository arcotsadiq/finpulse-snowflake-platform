USE ROLE ACCOUNTADMIN;
USE WAREHOUSE FINPULSE_WH;
USE DATABASE FINPULSE_DB;
USE SCHEMA ANALYTICS;

-- 1. Create User-Defined Table Function (UDTF)
CREATE OR REPLACE FUNCTION GET_ASSET_RISK_PROFILE(MIN_VOLUME FLOAT)
RETURNS TABLE (
  SYMBOL STRING,
  ASSET_NAME STRING,
  LATEST_PRICE FLOAT,
  CHANGE_24H_PCT FLOAT,
  VOLATILITY_TIER STRING,
  LIQUIDITY_RATIO FLOAT
)
AS
$$
  SELECT
    SYMBOL,
    ASSET_NAME,
    PRICE_USD AS LATEST_PRICE,
    CHANGE_24H_PCT,
    CASE 
      WHEN ABS(CHANGE_24H_PCT) >= 5.0 THEN 'HIGH_VOLATILITY'
      WHEN ABS(CHANGE_24H_PCT) >= 2.0 THEN 'MODERATE_VOLATILITY'
      ELSE 'STABLE'
    END AS VOLATILITY_TIER,
    ROUND(VOLUME_24H_USD / NULLIF(MARKET_CAP_USD, 0), 4) AS LIQUIDITY_RATIO
  FROM FINPULSE_DB.ANALYTICS.FACT_MARKET_PRICES
  WHERE VOLUME_24H_USD >= MIN_VOLUME
  QUALIFY ROW_NUMBER() OVER (PARTITION BY SYMBOL ORDER BY CAPTURED_AT DESC) = 1
$$;

-- 2. Create Secure View for Data Sharing / Provider Studio
CREATE OR REPLACE SECURE VIEW SECURE_MARKET_FEED_V AS
SELECT
  SYMBOL,
  ASSET_NAME,
  PRICE_USD,
  MARKET_CAP_USD,
  CHANGE_24H_PCT,
  CAPTURED_AT
FROM FINPULSE_DB.ANALYTICS.FACT_MARKET_PRICES;